
import nodemailer from "nodemailer";

const escapeHtml = (value = "") =>
  String(value).replace(/[&<>"']/g, (char) => {
    const entities = {
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&#39;",
    };
    return entities[char];
  });

const getTransporter = () => {
  const { SMTP_HOST, SMTP_PORT, SMTP_USER, SMTP_PASS } = process.env;

  if (!SMTP_HOST || !SMTP_PORT || !SMTP_USER || !SMTP_PASS) {
    throw new Error("Mailtrap SMTP environment variables are missing");
  }

  return nodemailer.createTransport({
    host: SMTP_HOST,
    port: Number(SMTP_PORT),
    secure: Number(SMTP_PORT) === 465,
    auth: {
      user: SMTP_USER,
      pass: SMTP_PASS,
    },
  });
};

const sendEmail = async ({ to, subject, html }) => {
  if (!to || !subject || !html) {
    throw new Error("Email recipient, subject, and content are required");
  }

  const transporter = getTransporter();

  const info = await transporter.sendMail({
    from: '"Twiller Testing" <test@twiller.local>',
    to,
    subject,
    html,
  });

  console.log("Mailtrap accepted test email:", info.messageId);

  return info;
};

// Send login verification OTP
export const sendOTP = async (email, otp) => {
  if (!email || !otp) {
    throw new Error("Email and OTP are required");
  }

  const safeOtp = escapeHtml(otp);

  await sendEmail({
    to: email,
    subject: "Twiller Login Verification OTP",
    html: `
      <div style="font-family: Arial, sans-serif; padding: 20px;">
        <h2>Twiller Login Verification</h2>
        <p>Use the following one-time password to verify your login:</p>
        <h1 style="letter-spacing: 5px;">${safeOtp}</h1>
        <p>This code is for your login verification.</p>
        <p>If you did not request this code, you can ignore this email.</p>
      </div>
    `,
  });
};

// Send subscription invoice after payment
export const sendSubscriptionInvoice = async (invoice = {}) => {
  const {
    email,
    userEmail,
    name,
    userName,
    plan,
    planName,
    amount,
    invoiceId,
    paymentId,
    date,
  } = invoice;

  const recipient = email || userEmail;

  if (!recipient) {
    throw new Error("Invoice recipient email is required");
  }

  const safeName = escapeHtml(name || userName || "Twiller User");
  const safePlan = escapeHtml(plan || planName || "Subscription");
  const safeAmount = escapeHtml(amount ?? "N/A");
  const safeInvoiceId = escapeHtml(invoiceId || "N/A");
  const safePaymentId = escapeHtml(paymentId || "N/A");
  const safeDate = escapeHtml(date || new Date().toISOString());

  await sendEmail({
    to: recipient,
    subject: "Your Twiller Subscription Invoice",
    html: `
      <div style="font-family: Arial, sans-serif; padding: 20px;">
        <h2>Twiller Subscription Invoice</h2>
        <p>Hello ${safeName},</p>
        <p>Thank you for your subscription.</p>
        <table cellpadding="8" cellspacing="0" border="1"
          style="border-collapse: collapse;">
          <tr><td><strong>Plan</strong></td><td>${safePlan}</td></tr>
          <tr><td><strong>Amount</strong></td><td>₹${safeAmount}</td></tr>
          <tr><td><strong>Invoice ID</strong></td><td>${safeInvoiceId}</td></tr>
          <tr><td><strong>Payment ID</strong></td><td>${safePaymentId}</td></tr>
          <tr><td><strong>Date</strong></td><td>${safeDate}</td></tr>
        </table>
        <p>This invoice email was generated by Twiller.</p>
      </div>
    `,
  });
};
